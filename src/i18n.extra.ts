type Tree = { [key: string]: unknown };

/** Merge `extra` into `target` in place (nested objects merged, strings replaced). */
export function deepMerge(target: Tree, extra: Tree): Tree {
  for (const [k, v] of Object.entries(extra)) {
    const cur = target[k];
    if (v && typeof v === "object" && !Array.isArray(v) && cur && typeof cur === "object") deepMerge(cur as Tree, v as Tree);
    else target[k] = v;
  }
  return target;
}
